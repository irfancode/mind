import { Link, useLocation } from "react-router-dom";

const navItems = [
  { path: "/", label: "Home", icon: HomeIcon },
  { path: "/explore", label: "Explore", icon: ExploreIcon },
  { path: "/compose", label: "Think", icon: ComposeIcon, primary: true },
  { path: "/people", label: "People", icon: PeopleIcon },
  { path: "/trust", label: "Trust", icon: TrustIcon },
];

export function MobileNav() {
  const location = useLocation();

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 border-t border-gray-100 bg-white/80 backdrop-blur-xl lg:hidden">
      <div className="flex items-center justify-around px-2 py-2">
        {navItems.map((item) => {
          const isActive = location.pathname === item.path;
          return (
            <Link
              key={item.path}
              to={item.path}
              className={`flex flex-col items-center gap-0.5 rounded-xl px-3 py-2 text-[10px] font-medium transition-all ${
                item.primary
                  ? "relative -mt-4 rounded-full bg-mind-600 px-4 py-3 text-white shadow-lg"
                  : isActive
                  ? "text-mind-600"
                  : "text-gray-500"
              }`}
            >
              <item.icon
                className={item.primary ? "h-6 w-6" : "h-5 w-5"}
              />
              {!item.primary && <span>{item.label}</span>}
            </Link>
          );
        })}
      </div>
    </nav>
  );
}

